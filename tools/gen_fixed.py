#!/usr/bin/env python3
"""Derive fixed Base58 transforms and prove every u64 accumulation bound.

The generated Rust is checked in; this script never runs during a crate build.
--check verifies the source without modifying it. --radix-digits 4 is an
experimental alternative; pass --output to keep it outside production source.
"""
import argparse
from pathlib import Path
import subprocess

MAX64 = (1 << 64) - 1
MAX32 = (1 << 32) - 1
ROOT = Path(__file__).resolve().parent.parent


def expression(column, start=0, end=None):
    if end is None:
        end = len(column)
    terms = []
    for j, coefficient in enumerate(column):
        if start <= j < end and coefficient:
            terms.append(f"x[{j}]" if coefficient == 1 else f"x[{j}] * {coefficient}")
    return " + ".join(terms) or "0"


def generate(radix_digits):
    radix = 58**radix_digits
    assert 58**10 - 1 <= MAX64 < 58**11
    assert 255 * (58**5 - 1) // 57 <= MAX32
    lines = [
        "// @generated by tools/gen_fixed.py; do not edit by hand.",
        "// Integer powers are derived from scratch; bounds are checked by the generator.",
        "// See docs/fixed-kernel.md for the algorithm and prior-art attribution.",
        f"const RADIX: u64 = {radix};",
    ]
    for size in (32, 64):
        words = size // 4
        groups = 0
        while radix**groups < 256**size:
            groups += 1
        # Removing temporary leading digits can never remove required zero bytes.
        for significant_bytes in range(1, size + 1):
            max_value = 256**significant_bytes - 1
            width = 0
            while 58**width <= max_value:
                width += 1
            assert groups * radix_digits - width >= size - significant_bytes
        enc = [
            [((1 << (32 * j)) // radix**k) % radix for j in range(words)]
            for k in range(groups)
        ]
        dec = [
            [((radix**j) >> (32 * k)) & MAX32 for j in range(groups)]
            for k in range(words)
        ]
        # The coefficients must represent the full power, not a truncated value.
        for j in range(words):
            assert sum(enc[k][j] * radix**k for k in range(groups)) == 1 << (32 * j)
        for j in range(groups):
            assert sum(dec[k][j] << (32 * k) for k in range(words)) == radix**j
        lines += [
            "#[inline]",
            f"pub(super) fn encode{size}(x: &[u64; {words}]) -> [u32; {groups}] {{",
            f"let mut y = [0; {groups}];",
            "let mut carry = 0;",
        ]
        carry_bound = 0
        for k, column in enumerate(enc):
            bound = sum(column) * MAX32 + carry_bound
            if bound > MAX64:
                split = words // 2
                assert sum(column[:split]) * MAX32 + carry_bound <= MAX64
                assert sum(column[split:]) * MAX32 <= MAX64
                assert 2 * (radix - 1) <= MAX64
                assert bound // radix <= MAX64
                lines += [
                    "// Normalize two bounded partial sums before adding this column.",
                    f"let low = {expression(column, end=split)} + carry;",
                    f"let high = {expression(column, start=split)};",
                    "let rem = low % RADIX + high % RADIX;",
                    f"y[{k}] = (rem % RADIX) as u32;",
                    "carry = low / RADIX + high / RADIX + rem / RADIX;",
                ]
            else:
                lines += [
                    f"let value = {expression(column) + ' + ' if any(column) else ''}carry;",
                    f"y[{k}] = (value % RADIX) as u32;",
                    "carry = value / RADIX;",
                ]
            carry_bound = bound // radix
        assert carry_bound == 0
        lines += ["debug_assert_eq!(carry, 0);", "y", "}"]
        lines += [
            "#[inline]",
            f"pub(super) fn decode{size}(x: &[u64; {groups}]) -> ([u32; {words}], u64) {{",
            f"let mut y = [0; {words}];",
            "let mut carry = 0;",
        ]
        carry_bound = 0
        for k, column in enumerate(dec):
            bound = sum(column) * (radix - 1) + carry_bound
            assert bound <= MAX64
            lines += [
                f"let value = {expression(column) + ' + ' if any(column) else ''}carry;",
                f"y[{k}] = value as u32;",
                "carry = value >> 32;",
            ]
            carry_bound = bound >> 32
        lines += ["(y, carry)", "}"]
    result = subprocess.run(
        ["rustfmt", "--edition", "2021"],
        input="\n".join(lines) + "\n", text=True, capture_output=True, check=True,
    )
    return result.stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--radix-digits", type=int, choices=(4, 5), default=5)
    parser.add_argument("--output", type=Path, default=ROOT / "src/fixed_tables.rs")
    args = parser.parse_args()
    if args.radix_digits != 5 and args.output == ROOT / "src/fixed_tables.rs":
        parser.error("experimental radix requires a separate --output")
    source = generate(args.radix_digits)
    if args.check:
        if args.output.read_text() != source:
            raise SystemExit(f"generated source differs: {args.output}")
    else:
        args.output.write_text(source)


if __name__ == "__main__":
    main()
